#!/usr/bin/env python3
"""Regenerate core/web_html.h from web/index.html"""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(root, 'web', 'index.html'), encoding='utf-8').read()
chunks = [html[i:i+8000] for i in range(0, len(html), 8000)]
out = '// generated by tools/gen_web.py from web/index.html - do not edit\n#pragma once\nstatic const char *WEB_INDEX_PARTS[] = {\n'
for c in chunks:
    out += 'R"HTMLX(' + c + ')HTMLX",\n'
out += '0};\n'
open(os.path.join(root, 'core', 'web_html.h'), 'w', encoding='utf-8').write(out)
print('ok', len(html), 'bytes')
