#!/usr/bin/env python3
"""Flatten tools/piece_shapes.py and write: ps4/piecedata.hpp, android PieceData.java, and the SHAPES block of web/index.html."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from piece_shapes import SHAPES
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def flatten(path, seg=12):
    t = path.split(); i = 0; pts = []; cur = (0.0, 0.0); polys = []
    while i < len(t):
        c = t[i]; i += 1
        if c == 'M':
            cur = (float(t[i]), float(t[i + 1])); i += 2; pts = [cur]
        elif c == 'L':
            cur = (float(t[i]), float(t[i + 1])); i += 2; pts.append(cur)
        elif c == 'Q':
            x1, y1, x, y = [float(v) for v in t[i:i + 4]]; i += 4; x0, y0 = cur
            for k in range(1, seg + 1):
                u = k / seg; pts.append(((1-u)**2*x0 + 2*(1-u)*u*x1 + u*u*x, (1-u)**2*y0 + 2*(1-u)*u*y1 + u*u*y))
            cur = (x, y)
        elif c == 'C':
            x1, y1, x2, y2, x, y = [float(v) for v in t[i:i + 6]]; i += 6; x0, y0 = cur
            for k in range(1, seg + 1):
                u = k / seg; a = (1-u)**3; b = 3*(1-u)**2*u; d = 3*(1-u)*u*u; e = u**3
                pts.append((a*x0 + b*x1 + d*x2 + e*x, a*y0 + b*y1 + d*y2 + e*y))
            cur = (x, y)
        elif c == 'Z':
            polys.append(pts); pts = []
        else: raise ValueError(c)
    return polys

def flat_shapes():
    out = {}
    for k, parts in SHAPES.items():
        out[k] = []
        for kind, path in parts:
            for poly in flatten(path):
                out[k].append((kind, [round(v, 2) for p in poly for v in p]))
    return out

FS = flat_shapes()
ORDER = "PNBRQK"

# ---- C++ (PS4)
cpp = ['// generated by tools/gen_pieces.py from tools/piece_shapes.py - do not edit\n#pragma once\nnamespace gfx {\nstruct PD { const float *pts; int n; int detail; };\n']
tbl = []
for ti, k in enumerate(ORDER):
    names = []
    for si, (kind, pts) in enumerate(FS[k]):
        nm = "PD_%s%d" % (k, si)
        cpp.append("static const float %s[] = {%s};\n" % (nm, ",".join("%g" % v for v in pts)))
        names.append("{%s,%d,%d}" % (nm, len(pts) // 2, 1 if kind == 'd' else 0))
    cpp.append("static const PD PIECE_%s[] = {%s};\n" % (k, ",".join(names)))
    tbl.append("{PIECE_%s,%d}" % (k, len(names)))
cpp.append("struct PS { const PD *p; int n; };\nstatic const PS PIECE_SHAPES[7] = {{0,0},%s};\n}\n" % ",".join(tbl))
open(os.path.join(root, 'ps4', 'piecedata.hpp'), 'w').write("".join(cpp))

# ---- web: replace the SHAPES block
js = "var SHAPES={" + ",".join('%s:[%s]' % (k, ",".join('["%s","%s"]' % ("d" if kind == 'd' else "p", " ".join("%g,%g" % (pts[i], pts[i+1]) for i in range(0, len(pts), 2))) for kind, pts in FS[k])) for k in ORDER) + "};"
p = os.path.join(root, 'web', 'index.html'); s = open(p, encoding='utf-8').read()
s2 = re.sub(r'/\*SHAPES\*/.*?/\*ENDSHAPES\*/', lambda m: '/*SHAPES*/' + js + '/*ENDSHAPES*/', s, flags=re.S)
if s2 == s and '/*SHAPES*/' not in s:
    s2 = re.sub(r'var SHAPES=\{.*?\};\nfunction shapeEl', lambda m: '/*SHAPES*/' + js + '/*ENDSHAPES*/\nfunction shapeEl', s, count=1, flags=re.S)
open(p, 'w', encoding='utf-8').write(s2)

# ---- Android (Java): polygons as strings, parsed at start-up
j = ['// generated by tools/gen_pieces.py - do not edit\npackage com.ps4chess.app.ui;\n\npublic final class PieceData {\n    private PieceData() {}\n    /** index 1..6 = pawn knight bishop rook queen king; each entry "x,y x,y ..." with a leading "d:" for detail shapes */\n    public static final String[][] SHAPES = {\n        {},\n']
for k in ORDER:
    j.append("        {%s},\n" % ",".join('"%s%s"' % ("d:" if kind == 'd' else "", " ".join("%g,%g" % (pts[i], pts[i+1]) for i in range(0, len(pts), 2))) for kind, pts in FS[k]))
j.append("    };\n}\n")
os.makedirs(os.path.join(root, 'android/app/src/main/java/com/ps4chess/app/ui'), exist_ok=True)
open(os.path.join(root, 'android/app/src/main/java/com/ps4chess/app/ui/PieceData.java'), 'w').write("".join(j))
print("pieces generated:", {k: len(v) for k, v in FS.items()})
