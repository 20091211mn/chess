#!/usr/bin/env python3
"""Rasterise Poppins (SIL Open Font License 1.1, (c) The Poppins Project Authors) into ps4/fontdata.hpp.
Usage: python3 tools/gen_font.py /path/to/Poppins-Medium.ttf /path/to/Poppins-Bold.ttf"""
import sys, base64, os
from PIL import Image, ImageDraw, ImageFont
medium, bold = sys.argv[1], sys.argv[2]
FACES = [(medium, 18, None), (medium, 22, None), (medium, 28, None), (bold, 28, None), (bold, 36, None), (bold, 48, None),
         (bold, 72, set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 "))]
out = ['// generated by tools/gen_font.py - Poppins, SIL Open Font License 1.1\n#pragma once\n#include <stdint.h>\nnamespace fontdata {\n'
       'struct G { uint32_t off; uint8_t w, h; int8_t bx, by; uint8_t adv; };\n'
       'struct F { int px, asc, lh; const G *g; const char *const *parts; };\n']
facerefs = []
for fi, (path, px, subset) in enumerate(FACES):
    font = ImageFont.truetype(path, px)
    asc, desc = font.getmetrics()
    nibbles = []
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        if subset is not None and ch not in subset:
            glyphs.append((0, 0, 0, 0, 0, 0)); continue
        bb = font.getbbox(ch, anchor='ls')
        w, h = bb[2] - bb[0], bb[3] - bb[1]
        if w <= 0 or h <= 0:
            glyphs.append((0, 0, 0, 0, 0, adv)); continue
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=font, fill=255, anchor='ls')
        off = len(nibbles)
        data = im.tobytes()
        nibbles.extend((b + 8) // 17 if b < 248 else 15 for b in data)
        glyphs.append((off, w, h, bb[0], bb[1], adv))
    if len(nibbles) % 2: nibbles.append(0)
    packed = bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
    b64 = base64.b64encode(packed).decode()
    out.append('static const G G%d[95] = {%s};\n' % (fi, ','.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs)))
    parts = [b64[i:i + 6000] for i in range(0, len(b64), 6000)]
    out.append('static const char *const P%d[] = {%s,0};\n' % (fi, ','.join('"%s"' % p for p in parts)))
    facerefs.append('{%d,%d,%d,G%d,P%d}' % (px, asc, asc + desc, fi, fi))
    print('face', fi, px, 'px:', len(packed), 'bytes packed')
out.append('static const F FACES[%d] = {%s};\n}\n' % (len(FACES), ','.join(facerefs)))
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'ps4', 'fontdata.hpp'), 'w').write(''.join(out))
